#!/usr/bin/env bash
# Opens the winget-pkgs PR for a published LogDeck release ("Update: wisecort.LogDeck to X.Y.Z").
# Usage: scripts/update-winget.sh 1.5.0 [--dry-run]
# Needs: gh logged in (locally) or GH_TOKEN with public_repo (release workflow), and the
# github.com/wisecort/winget-pkgs fork. Manifests come from scripts/winget-manifests.mjs.
set -euo pipefail
VERSION="${1:?usage: scripts/update-winget.sh <version> [--dry-run]}"
DRY="${2:-}"
ID="wisecort.LogDeck"
EXE="LogDeck-${VERSION}-x64.exe"
SUMS="$(gh release download "v${VERSION}" -R wisecort/LogDeck -p 'SHA256SUMS-Windows.txt' -O -)"
# sha256sum on Windows marks binary mode with "*" before the name.
SHA="$(awk -v f="$EXE" '{ n = $2; sub(/^\*/, "", n) } n == f { print $1 }' <<<"$SUMS")"
[[ ${#SHA} -eq 64 ]] || { echo "checksum de ${EXE} não encontrado na release v${VERSION}"; exit 1; }

WORK="$(mktemp -d)"
node scripts/winget-manifests.mjs "$VERSION" "$SHA" "$WORK/out"
cat "$WORK/out/${VERSION}/${ID}.installer.yaml"
if [[ "$DRY" == "--dry-run" ]]; then
  echo "(dry-run: nada enviado; manifestos em $WORK/out/${VERSION})"
  exit 0
fi

gh auth setup-git
git clone -q --depth 1 --filter=blob:none --sparse https://github.com/wisecort/winget-pkgs.git "$WORK/wp"
cd "$WORK/wp"
git sparse-checkout set --no-cone /manifests/w/wisecort/
git fetch -q --depth 1 https://github.com/microsoft/winget-pkgs.git master
BRANCH="${ID}-${VERSION}"
git checkout -q -b "$BRANCH" FETCH_HEAD
DEST="manifests/w/wisecort/LogDeck/${VERSION}"
mkdir -p "$DEST"
cp "$WORK/out/${VERSION}/"*.yaml "$DEST/"
git add "$DEST"
git -c user.name="Matheus Corteletti" -c user.email="61605704+wisecort@users.noreply.github.com" commit -qm "Update: ${ID} to ${VERSION}"
git push -q -f origin "$BRANCH"

BODY="$WORK/body.md"
cat >"$BODY" <<MD
## 📖 Description

Update: **${ID}** to **${VERSION}** (release: https://github.com/wisecort/LogDeck/releases/tag/v${VERSION}).

Generated by LogDeck's release workflow from the previous manifest: only the version, installer URL/SHA-256 and release date change. The NSIS ProductCode is derived from the app id and is the same in every version.

## ✅ Checklist

- [x] Signed the [Contributor License Agreement](https://cla.opensource.microsoft.com)
- [ ] Linked to an issue (if applicable)

## 📦 Manifest Checklist

- [x] Checked that there aren't other open [pull requests](https://github.com/microsoft/winget-pkgs/pulls) for the same manifest update/change
- [x] This PR only modifies one (1) manifest
- [ ] Validated manifest locally with \`winget validate --manifest <path>\` (generated on Linux CI; relying on the validation pipeline)
- [ ] Tested manifest locally with \`winget install --manifest <path>\`
- [x] Manifest conforms to the [1.12 schema](https://github.com/microsoft/winget-pkgs/tree/master/doc/manifest/schema/1.12.0)
MD
if [[ -n "$(gh pr list -R microsoft/winget-pkgs --head "$BRANCH" --state open --json number --jq '.[0].number')" ]]; then
  echo "PR já aberto para ${BRANCH}; branch atualizada"
else
  gh pr create -R microsoft/winget-pkgs --head "wisecort:${BRANCH}" --base master --title "Update: ${ID} to ${VERSION}" --body-file "$BODY"
fi
